const resolvedDictionaries: Record<Language, Record<TranslationKey, string>> = {
  es: dictionaries.es,
  en: english,
  pt: portuguese,
}

const dateLocales = { es, en: enUS, pt: ptBR } as const

interface LanguageContextValue {
  language: Language
  setLanguage: (language: Language) => void
  t: (key: TranslationKey) => string
  dateLocale: typeof es
  locale: string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

function isLanguage(value: string | null): value is Language {
  return languages.some((language) => language.code === value)
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("es")

  useEffect(() => {
    const storedLanguage = window.localStorage.getItem(storageKey)
    if (isLanguage(storedLanguage)) setLanguageState(storedLanguage)
  }, [])

  const setLanguage = (nextLanguage: Language) => {
    setLanguageState(nextLanguage)
    window.localStorage.setItem(storageKey, nextLanguage)
    document.documentElement.lang = nextLanguage
  }

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t: (key) => resolvedDictionaries[language][key] ?? dictionaries.es[key],
    dateLocale: dateLocales[language],
    locale: language === "pt" ? "pt-BR" : language === "en" ? "en-US" : "es-ES",
  }), [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error("useLanguage must be used within LanguageProvider")
  return context
}
